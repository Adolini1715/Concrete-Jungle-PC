#!/usr/bin/env python3
"""src/osd_font.h: ASCII 32-126 as 8-bit coverage, 12x22 cells, from DejaVu Sans Mono Bold
(Bitstream Vera / DejaVu licence: free to embed). Used by the on-screen messages (src/osd.c)."""
from PIL import Image, ImageDraw, ImageFont
W, H = 12, 22
f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf', 18)
out = ['/* generated by tools/art/gen_osd_font.py (DejaVu Sans Mono Bold 18 px) */',
       '#define OSD_FW %d' % W, '#define OSD_FH %d' % H,
       'static const unsigned char osd_font[95][%d] = {' % (W * H)]
for c in range(32, 127):
    im = Image.new('L', (W, H), 0)
    d = ImageDraw.Draw(im)
    d.text((W / 2, H / 2 + 1), chr(c), fill=255, font=f, anchor='mm')
    px = list(im.getdata())
    out.append('{' + ','.join(str(v) for v in px) + '},')
out.append('};')
open('/home/claude/pcj-native/src/osd_font.h', 'w').write('\n'.join(out) + '\n')
