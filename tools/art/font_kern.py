#!/usr/bin/env python3
"""Generate src/font_kern.h: ink extents of every glyph of the front-end fonts.

  font_kern.py <font dump log> <texture dump dir> > src/font_kern.h

<font dump log>: the [FONT] lines a run with CJ_FONT_DUMP=1 prints (each font's ASCII glyph
metrics). <texture dump dir>: a CJ_TEX_DUMP folder with the three font textures. For each glyph:
where its ink starts and ends inside its cell, in 1/16 source pixels.

The game's glyph UVs are pixel / (size - 1) rather than pixel / size (an off-by-one that slides every
cell right by up to a texel across the atlas and cuts the first ink column off the right-hand
glyphs). src/recomp_manual.c corrects them when a font loads and widens each cell by one blank column
on the left (every glyph's ink starts on its true first column, and the column before it is empty),
so the extents here are measured from the true cell and given in that padded cell. src/recomp_manual.c picks each glyph's m_Kern from
these for the scale the text is drawn at, so every pair of letters ends up the same distance apart.
"""
import re, sys
import numpy as np
from PIL import Image

TEX = {'0700000a': '9594b0b78805ac05_256x64_0E.png',   # small
       '07000004': '8662cbf2181cf340_256x128_0E.png',  # menu (bold)
       '0700000c': '531ef27bd120d318_256x128_0E.png'}  # title (bold italic)
fonts, cur = {}, None
for l in open(sys.argv[1]):
    m = re.search(r"\[FONT\] font=\w+ hash=(\w+)", l)
    if m:
        cur = None if m.group(1) in fonts else fonts.setdefault(m.group(1), {})
        continue
    m = re.search(r"\[FONT\] '(.)' w=(\d+) h=(\d+) kern=(\d+) uv=([\d.]+),([\d.]+)-([\d.]+),([\d.]+)", l)
    if m and cur is not None:
        cur[m.group(1)] = [int(x) for x in m.groups()[1:4]] + [float(x) for x in m.groups()[4:]]
print("/* Generated by tools/art/font_kern.py: per glyph 0x21..0x7E, ink start and end in its corrected,")
print(" * left-padded cell (1/16 source pixels; 0,0 = no glyph). Keyed by the font's original 'a' u0. */")
print("typedef struct { float a_u0; unsigned short ink[94][2]; } FontInk;")
print("static const FontInk k_font_ink[] = {")
for hh, ch in fonts.items():
    if hh not in TEX: continue
    a = np.asarray(Image.open(sys.argv[2] + '/' + TEX[hh]).convert('RGBA'))[..., 3].astype(int)
    H, W = a.shape
    cells = []
    for c in range(0x21, 0x7f):
        g = ch.get(chr(c))
        if not g:
            cells.append('{0,0}'); continue
        w, h, k, u0, v0, u1, v1 = g
        x0, y0 = round(u0 * (W - 1)), round(v0 * (H - 1))   # the true cell (see above)
        cell = a[y0:y0 + h, x0:x0 + w]
        cols = np.nonzero((cell >= 128).any(0))[0]
        if len(cols) == 0: cols = np.nonzero((cell > 8).any(0))[0]
        if len(cols) == 0:
            cells.append('{0,0}'); continue
        cells.append('{%d,%d}' % (16 + cols.min() * 16, 16 + (cols.max() + 1) * 16))   # padded cell
    print("    { %.4ff, {%s} },  /* %s */" % (ch['a'][3], ",".join(cells), hh))
print("};")
